import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const generatedPath = path.join(
  root,
  "packages/adapter-web/src/product-ui-assets.generated.ts",
);

export const PRODUCT_UI_TEXT_ASSETS = Object.freeze([
  ["PRODUCT_UI_TOKENS_CSS", "docs/assets/brand/mind-diary-tokens.css"],
  ["PRODUCT_UI_SHELL_CSS", "packages/adapter-web/src/ui-shell.css"],
  ["PRODUCT_SHELL_INTERACTIONS_JAVASCRIPT", "packages/adapter-web/assets/shell-interactions.js"],
  ["PRODUCT_UI_CLIENT_JAVASCRIPT", "packages/adapter-web/assets/product-ui-client.js"],
  ["PRODUCT_ORDINARY_MINDS_CLIENT_JAVASCRIPT", "packages/adapter-web/assets/ordinary-minds-client.js"],
  ["PRODUCT_MARKDOWN_IMPORT_CLIENT_JAVASCRIPT", "packages/adapter-web/assets/markdown-import-client.js"],
  ["PRODUCT_EXPORT_CLIENT_JAVASCRIPT", "packages/adapter-web/assets/export-client.js"],
  ["PRODUCT_COLLABORATION_CLIENT_JAVASCRIPT", "packages/adapter-web/assets/collaboration-client.js"],
  ["PRODUCT_CONNECTIONS_CLIENT_JAVASCRIPT", "packages/adapter-web/assets/connections-client.js"],
  ["PRODUCT_VISIBILITY_CATALOG_CLIENT_JAVASCRIPT", "packages/adapter-web/assets/visibility-catalog-client.js"],
]);

function generatedSource() {
  const exports = PRODUCT_UI_TEXT_ASSETS.map(([name, relativePath]) => {
    const body = fs.readFileSync(path.join(root, relativePath), "utf8");
    return `export const ${name} = ${JSON.stringify(body)};`;
  }).join("\n\n");
  return `// Generated by scripts/generate-product-ui-assets.mjs. Do not edit directly.\n${exports}\n`;
}

export function checkProductUiAssetsGenerated() {
  const expected = generatedSource();
  const actual = fs.existsSync(generatedPath)
    ? fs.readFileSync(generatedPath, "utf8")
    : null;
  if (actual !== expected) {
    throw new Error(
      "Product UI assets are stale. Run npm run generate:product-ui-assets and commit the result.",
    );
  }
}

if (process.argv.includes("--check")) {
  checkProductUiAssetsGenerated();
} else {
  fs.writeFileSync(generatedPath, generatedSource());
}
