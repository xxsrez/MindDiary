import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sourcePath = resolve(
  root,
  "packages/adapter-mcp/guidance/service-guidance.md",
);
const generatedPath = resolve(
  root,
  "packages/adapter-mcp/src/service-guidance.generated.ts",
);

function parseArguments(argv) {
  let check = false;
  let marketplaceRoot = null;
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--check") {
      check = true;
    } else if (argument === "--marketplace-root") {
      marketplaceRoot = argv[index + 1] ?? null;
      index += 1;
    } else {
      throw new TypeError(`Unsupported argument: ${argument}`);
    }
  }
  if (marketplaceRoot === "") throw new TypeError("Marketplace root is empty.");
  return { check, marketplaceRoot };
}

const options = parseArguments(process.argv.slice(2));
const source = await readFile(sourcePath, "utf8");
if (!source.endsWith("\n")) throw new TypeError("Guidance source must end with LF.");
const sha256 = `sha256:${createHash("sha256").update(source).digest("hex")}`;
const hostSpecificBoundary = "The hosted guide is complete without local tools. Use the separate macOS companion reference only when prepare_local_file, upload_prepared_file or download_bundle_file is actually present; otherwise do not call or emulate those tools.";
const generated = `// Generated by scripts/sync-mind-diary-service-guidance.mjs.\n` +
  `// Edit packages/adapter-mcp/guidance/service-guidance.md instead.\n` +
  `export const MIND_DIARY_SERVICE_GUIDANCE_VERSION = "2026-09-18" as const;\n` +
  `export const MIND_DIARY_SERVICE_GUIDANCE_SHA256 = ${JSON.stringify(sha256)} as const;\n` +
  `export const MIND_DIARY_SERVICE_GUIDANCE_MARKDOWN = ${JSON.stringify(source)} as const;\n` +
  `export const MIND_DIARY_HOST_SPECIFIC_BOUNDARY = ${JSON.stringify(hostSpecificBoundary)} as const;\n`;

async function sync(path, expected) {
  if (options.check) {
    const actual = await readFile(path, "utf8").catch(() => null);
    if (actual !== expected) throw new TypeError(`Generated guidance is stale: ${path}`);
    return;
  }
  await writeFile(path, expected, "utf8");
}

await sync(generatedPath, generated);
if (options.marketplaceRoot !== null) {
  await sync(
    resolve(
      options.marketplaceRoot,
      "plugins/mind-diary/skills/mind-diary/references/service-guidance.md",
    ),
    source,
  );
}

process.stdout.write(`${options.check ? "checked" : "updated"} ${sha256}\n`);
